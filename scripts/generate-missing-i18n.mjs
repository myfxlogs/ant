#!/usr/bin/env node
/**
 * Generates missing i18n resource files for all locales.
 * Reads scripts/i18n-missing-keys.json and creates:
 *   frontend/src/i18n/resources/{locale}/{namespace}.ts
 * Then updates each locale's index.ts to import them.
 */

import * as fs from 'fs';
import * as path from 'path';

const ROOT = path.resolve(process.cwd());
const RES_DIR = path.join(ROOT, 'frontend', 'src', 'i18n', 'resources');
const LOCALES = ['en', 'zh-cn', 'zh-tw', 'ja', 'vi'];
const missingData = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'i18n-missing-keys.json'), 'utf-8'));

// Namespaces that already have resource files (don't create new ones, merge instead)
const EXISTING_NS = new Set(['admin', 'accounts', 'dashboard', 'errors', 'landing', 'marketplace', 'strategy']);

function setNested(obj, keyPath, value) {
  const parts = keyPath.split('.');
  let current = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!current[parts[i]]) current[parts[i]] = {};
    current = current[parts[i]];
  }
  current[parts[parts.length - 1]] = value;
}

function pascalCase(s) {
  return s.replace(/(^|_)(.)/g, (_, __, c) => c.toUpperCase());
}

// For each namespace, build the nested object
const nsObjects = {};
for (const [ns, entries] of Object.entries(missingData)) {
  const obj = {};
  for (const e of entries) {
    // The key is like "admin.account.title" — remove the namespace prefix for nesting
    const relPath = e.key.substring(ns.length + 1);
    setNested(obj, relPath, e.dv);
  }
  nsObjects[ns] = obj;
}

// Generate resource files for each namespace × locale
const newNamespaces = [];
for (const ns of Object.keys(nsObjects)) {
  if (EXISTING_NS.has(ns)) {
    // Need to merge into existing file — skip for now, handle separately
    continue;
  }
  newNamespaces.push(ns);
  const pascalName = pascalCase(ns);

  for (const locale of LOCALES) {
    const dir = path.join(RES_DIR, locale);
    fs.mkdirSync(dir, { recursive: true });
    const filePath = path.join(dir, `${ns}.ts`);

    // For non-en locales, use English as placeholder (same structure)
    const content = `// Auto-generated by scripts/generate-missing-i18n.mjs\n` +
      `// TODO: Translate to ${locale}\n` +
      `const ${pascalName} = ${JSON.stringify({ [ns]: nsObjects[ns] }, null, 2)} as const;\n` +
      `export default ${pascalName};\n`;
    fs.writeFileSync(filePath, content);
  }
  console.log(`  Created ${ns}.ts for ${LOCALES.length} locales`);
}

// Now handle existing namespaces that need merging
// For admin, accounts, dashboard, errors — these are auto-generated from textproto
// We need to add the missing keys to the textproto files + map.json
// For now, create supplementary files that will be merged
const supplementNamespaces = [];
for (const ns of Object.keys(nsObjects)) {
  if (!EXISTING_NS.has(ns)) continue;
  supplementNamespaces.push(ns);
  const pascalName = pascalCase(ns + '_extra');
  for (const locale of LOCALES) {
    const dir = path.join(RES_DIR, locale);
    const filePath = path.join(dir, `${ns}_extra.ts`);
    const content = `// Auto-generated supplementary keys for ${ns}\n` +
      `// TODO: Translate to ${locale}\n` +
      `const ${pascalName} = ${JSON.stringify({ [ns]: nsObjects[ns] }, null, 2)} as const;\n` +
      `export default ${pascalName};\n`;
    fs.writeFileSync(filePath, content);
  }
  console.log(`  Created ${ns}_extra.ts for ${LOCALES.length} locales (supplement)`);
}

// Update each locale's index.ts
for (const locale of LOCALES) {
  const indexPath = path.join(RES_DIR, locale, 'index.ts');
  let content = fs.readFileSync(indexPath, 'utf-8');

  // Find the mergeResources call
  const mergeMatch = content.match(/const \w+ = mergeResources\(([\s\S]*?)\) as const;/);
  if (!mergeMatch) {
    console.error(`  Could not find mergeResources in ${indexPath}`);
    continue;
  }

  let imports = '';
  let mergeArgs = mergeMatch[1];

  // Add imports and merge args for new namespaces
  for (const ns of [...newNamespaces, ...supplementNamespaces]) {
    const importName = pascalCase(ns) + (supplementNamespaces.includes(ns) ? 'Extra' : '');
    const fileName = ns + (supplementNamespaces.includes(ns) ? '_extra' : '');

    // Check if already imported
    if (content.includes(`./${fileName}`)) continue;

    imports += `import ${importName} from './${fileName}';\n`;
    mergeArgs += `  ${importName},\n`;
  }

  if (imports) {
    // Add imports before the mergeResources call
    const mergeStart = content.indexOf('const ');
    const mergeSection = content.substring(mergeStart);
    content = content.substring(0, mergeStart) + imports + '\n' + mergeSection;

    // Replace mergeResources args
    content = content.replace(
      /const (\w+) = mergeResources\(([\s\S]*?)\) as const;/,
      (match, varName, args) => {
        // Rebuild args with new entries
        let newArgs = args.trimEnd();
        for (const ns of [...newNamespaces, ...supplementNamespaces]) {
          const importName = pascalCase(ns) + (supplementNamespaces.includes(ns) ? 'Extra' : '');
          const fileName = ns + (supplementNamespaces.includes(ns) ? '_extra' : '');
          if (!newArgs.includes(importName)) {
            newArgs += `  ${importName},\n`;
          }
        }
        return `const ${varName} = mergeResources(${newArgs}) as const;`;
      }
    );

    fs.writeFileSync(indexPath, content);
    console.log(`  Updated ${locale}/index.ts`);
  }
}

console.log(`\nDone. New namespaces: ${newNamespaces.length}, supplements: ${supplementNamespaces.length}`);
