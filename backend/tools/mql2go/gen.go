// ── Output helpers ───────────────────────────────────────────────

func (g *generator) emit(s string) {
	g.b.WriteString(strings.Repeat("\t", g.indent))
	g.b.WriteString(s)
	g.b.WriteByte('\n')
}

func (g *generator) emitf(format string, args ...interface{}) {
	g.emit(fmt.Sprintf(format, args...))
}

func (g *generator) goStructName() string {
	if g.intent.Meta.Name != "" {
		return g.intent.Meta.Name
	}
	return "ImportedStrategy"
}

func (g *generator) goPkgName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(unicode.ToLower(r))
		}
	}
	if b.Len() == 0 {
		return "strategy"
	}
	return b.String()
}

// ── Expression helpers ───────────────────────────────────────────

func nonEmpty(ss []string) []string {
	var out []string
	for _, s := range ss {
		if s != "" {
			out = append(out, s)
		}
	}
	return out
}

func stripQuotes(s string) string {
	if len(s) >= 2 && s[0] == '\'' && s[len(s)-1] == '\'' {
		return s[1 : len(s)-1]
	}
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		return s[1 : len(s)-1]
	}
	return s
}

func mqlToGoType(t string) string {
	switch t {
	case "int", "long", "uint":
		return "int"
	case "double", "float":
		return "decimal.Decimal"
	case "bool":
		return "bool"
	default:
		return "string"
	}
}

func goSignalAction(a OrderAction) string {
	switch a {
	case ActionMarketBuy:
		return "sdk.ActionBuy"
	case ActionMarketSell:
		return "sdk.ActionSell"
	case ActionBuyLimit:
		return "sdk.ActionBuyLimit"
	case ActionSellLimit:
		return "sdk.ActionSellLimit"
	case ActionBuyStop:
		return "sdk.ActionBuyStop"
	case ActionSellStop:
		return "sdk.ActionSellStop"
	}
	return "sdk.ActionNone"
}

func goFillPolicy(a OrderAction) string {
	switch a {
	case ActionMarketBuy, ActionMarketSell:
		return "sdk.FillIOC"
	}
	return "sdk.FillReturn"
}

func prefixRef(expr string) string {
	// If a bare identifier (no prefix), add "s."
	if expr == "" || strings.HasPrefix(expr, "s.") || strings.HasPrefix(expr, "ctx.") {
		return expr
	}
	if strings.Contains(expr, ".") || strings.Contains(expr, "(") || strings.Contains(expr, "\"") {
		return expr // already qualified or literal
	}
	return "s." + expr
}

func pyToGoExpr(expr string) string {
	if expr == "" {
		return expr
	}
	// self. → s.
	expr = strings.ReplaceAll(expr, "self.", "s.")
	// Python logical operators → Go
	expr = strings.ReplaceAll(expr, " and ", " && ")
	expr = strings.ReplaceAll(expr, " or ", " || ")
	expr = strings.ReplaceAll(expr, " not ", " ! ")
	// Remove Decimal(str(...)) wrapper
	expr = strings.ReplaceAll(expr, "Decimal(str(", "")
	expr = strings.ReplaceAll(expr, "'", "")
	// MQL builtins → ctx methods
	expr = replaceWord(expr, "Ask", "ctx.Ask().InexactFloat64()")
	expr = replaceWord(expr, "Bid", "ctx.Bid().InexactFloat64()")
	expr = replaceWord(expr, "Point", "ctx.Point().InexactFloat64()")
	expr = strings.ReplaceAll(expr, "Symbol()", "ctx.Symbol()")
	return expr
}

func paramGoType(t ParamType) string {
	switch t {
	case ParamInt:
		return "int32"
	case ParamDouble:
		return "float64"
	case ParamString:
		return "string"
	case ParamBool:
		return "bool"
	default:
		return "string"
	}
}

func isNumeric(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if (c < '0' || c > '9') && c != '.' && c != '-' {
			return false
		}
	}
	return true
}

func replaceWord(s, old, new string) string {
	var b strings.Builder
	i := 0
	for i < len(s) {
		if i+len(old) <= len(s) && s[i:i+len(old)] == old {
			before := i == 0 || !isWordChar(s[i-1])
			after := i+len(old) == len(s) || !isWordChar(s[i+len(old)])
			if before && after {
				b.WriteString(new)
				i += len(old)
				continue
			}
		}
		b.WriteByte(s[i])
		i++
	}
	return b.String()
}

func isWordChar(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_'
}

func (g *generator) convertParams(expr string) string {
	for _, p := range g.intent.Params {
		if p.Type == ParamInt {
			expr = replaceWord(expr, p.Name, "float64(s."+p.Name+")")
		} else {
			expr = replaceWord(expr, p.Name, "s."+p.Name)
		}
	}
	return expr
}
