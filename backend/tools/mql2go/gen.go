package mql2go

import (
	"fmt"
	"strings"
	"unicode"
)

// Generate produces Go strategy source code from a StrategyIntent.
func Generate(intent *StrategyIntent) string {
	g := &generator{intent: intent}
	return g.generate()
}

type generator struct {
	intent *StrategyIntent
	b      strings.Builder
	indent int
}

func (g *generator) generate() string {
	g.b.Reset()
	g.genHeader()
	g.genStruct()
	g.genOnInit()
	g.genOnBar()
	if g.intent.Timer != nil {
		g.genOnTimer()
	}
	g.genOnDeinit()
	g.genHelpers()
	return g.b.String()
}

// ── Header ────────────────────────────────────────────────────────

func (g *generator) genHeader() {
	name := g.goStructName()
	pkg := g.goPkgName(name)
	g.emit("// Code generated by mql2go. DO NOT EDIT.")
	g.emitf("// Source: %s strategy", g.intent.Meta.MQLVersion)
	g.emitf("package %s", pkg)
	g.emit("")
	g.emit("import (")
	g.indent++
	g.emit(`"github.com/shopspring/decimal"`)
	g.emit(`"anttrader/strategy/sdk"`)
	g.indent--
	g.emit(")")
	g.emit("")
}

// ── Struct ────────────────────────────────────────────────────────

func (g *generator) genStruct() {
	name := g.goStructName()
	g.emitf("// %s is an imported strategy.", name)
	g.emitf("type %s struct {", name)
	g.indent++
	for _, sv := range g.intent.State {
		goType := mqlToGoType(sv.GoType)
		g.emitf("%s %s", sv.Name, goType)
	}
	for _, p := range g.intent.Params {
		g.emitf("%s %s", p.Name, paramGoType(p.Type))
	}
	g.emit("magic int32")
	g.emit("lotSize decimal.Decimal")
	g.emit("hedging bool")
	g.indent--
	g.emit("}")
	g.emit("")
	g.emitf("var _ sdk.Strategy = (*%s)(nil)", name)
	g.emit("")
}

// ── on_init ──────────────────────────────────────────────────────

func (g *generator) genOnInit() {
	name := g.goStructName()
	g.emitf("func (s *%s) OnInit(ctx sdk.Context) error {", name)
	g.indent++

	for _, p := range g.intent.Params {
		g.emitParam(p)
	}

	if g.intent.Timer != nil {
		g.emitf("ctx.SetTimer(%d)", g.intent.Timer.IntervalSeconds)
	}

	g.emit("s.hedging = ctx.Mode() == sdk.ModeHedging")
	g.emit("return nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── on_bar ────────────────────────────────────────────────────────

func (g *generator) genOnBar() {
	name := g.goStructName()
	g.emitf("func (s *%s) OnBar(ctx sdk.Context, tf string) (*sdk.Signal, error) {", name)
	g.indent++

	if g.intent.Execution.Kind == ExecOnBar {
		g.emit("if tf != ctx.Timeframe() {")
		g.emit("    return nil, nil")
		g.emit("}")
	}
	// ExecOnTick: no timeframe filter — execute on every tick

	g.emit("bars := ctx.Bars()")
	g.emit("_ = bars")
	g.emit("")

	// Indicators
	for _, spec := range g.intent.Indicators {
		g.emitIndicator(spec)
	}

	// Exits
	for _, exit := range g.intent.Exit {
		g.emitExit(exit)
	}

	// Modifies (OrderModify / PositionModify)
	for _, mr := range g.intent.Modifies {
		g.emitModify(mr)
	}

	// Entries
	for _, entry := range g.intent.Entry {
		g.emitEntry(entry)
	}

	g.emit("return nil, nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── Entry ─────────────────────────────────────────────────────────

func (g *generator) emitEntry(e EntryRule) {
	condParts := nonEmpty(e.Conditions)
	if len(condParts) > 0 {
		cond := strings.Join(condParts, " && ")
		cond = pyToGoExpr(g.convertParams(cond))
		g.emitf("if %s {", cond)
		g.indent++
	}

	action := goSignalAction(e.Action)
	volume := prefixRef(pyToGoExpr(e.Volume))
	magic := prefixRef(pyToGoExpr(e.Magic))
	if volume == "" || volume == "s." {
		volume = "s.lotSize"
	}
	if magic == "" || magic == "s." {
		magic = "s.magic"
	}
	fill := goFillPolicy(e.Action)

	g.emit("sig := &sdk.Signal{")
	g.emitf("    Action: %s,", action)
	if volume == "s.lotSize" {
		g.emitf("    Volume: %s,", volume)
	} else {
		g.emitf("    Volume: decimal.NewFromFloat(float64(%s)),", volume)
	}
	if e.StopLoss != "" && e.StopLoss != "0" && e.StopLoss != "0.0" {
		slExpr := pyToGoExpr(g.convertParams(e.StopLoss))
		g.emitf("    StopLoss: decimal.NewFromFloat(%s),", slExpr)
	}
	if e.TakeProfit != "" && e.TakeProfit != "0" && e.TakeProfit != "0.0" {
		tpExpr := pyToGoExpr(g.convertParams(e.TakeProfit))
		g.emitf("    TakeProfit: decimal.NewFromFloat(%s),", tpExpr)
	}
	if e.Comment != "" {
		g.emitf("    Comment: \"%s\",", stripQuotes(e.Comment))
	}
	g.emitf("    Magic: %s,", magic)
	g.emitf("    FillPolicy: %s,", fill)
	g.emit("}")
	g.emit("return sig, nil")

	if len(condParts) > 0 {
		g.indent--
		g.emit("}")
	}
}

// ── Exit ──────────────────────────────────────────────────────────

func (g *generator) emitExit(e ExitRule) {
	magic := pyToGoExpr(e.MagicVal)
	if magic == "" {
		magic = "s.magic"
	}

	switch e.Trigger {
	case TriggerMagic:
		g.emitf("for _, pos := range ctx.Broker().Positions(%s) {", magic)
		g.emit("    ctx.Broker().PositionClose(pos.Ticket, decimal.Zero)")
		g.emit("}")
	case TriggerDelete:
		g.emitf("for _, ord := range ctx.Broker().Orders(%s) {", magic)
		g.emit("    ctx.Broker().OrderDelete(ord.Ticket)")
		g.emit("}")
	case TriggerAll:
		g.emit("s.closeAll(ctx)")
	}
}

// ── Modify (OrderModify / PositionModify) ─────────────────────────

func (g *generator) emitModify(mr ModifyRule) {
	magic := pyToGoExpr(mr.MagicVal)
	if magic == "" {
		magic = "s.magic"
	}

	if mr.Condition != "" {
		cond := pyToGoExpr(g.convertParams(mr.Condition))
		g.emitf("if %s {", cond)
		g.indent++
	}

	g.emitf("for _, pos := range ctx.Broker().Positions(%s) {", magic)
	g.indent++

	slExpr := "decimal.Zero"
	tpExpr := "decimal.Zero"
	if mr.StopLoss != "" && mr.StopLoss != "0" && mr.StopLoss != "0.0" {
		slExpr = "decimal.NewFromFloat(" + pyToGoExpr(g.convertParams(mr.StopLoss)) + ")"
	}
	if mr.TakeProfit != "" && mr.TakeProfit != "0" && mr.TakeProfit != "0.0" {
		tpExpr = "decimal.NewFromFloat(" + pyToGoExpr(g.convertParams(mr.TakeProfit)) + ")"
	}

	g.emitf("ctx.Broker().PositionModify(pos.Ticket, %s, %s)", slExpr, tpExpr)
	g.indent--
	g.emit("}")

	if mr.Condition != "" {
		g.indent--
		g.emit("}")
	}
}

// ── on_timer ────────────────────────────────────────────────────

func (g *generator) genOnTimer() {
	name := g.goStructName()
	g.emit("")
	g.emitf("func (s *%s) OnTimer(ctx sdk.Context) error {", name)
	g.indent++
	g.emit("margin := ctx.Broker().Account().MarginLevel")
	g.emit(`threshold := ctx.ParamDecimal("MarginThreshold", decimal.NewFromInt(50))`)
	g.emit("if margin.LessThan(threshold) {")
	g.emit("    s.closeAll(ctx)")
	g.emit("}")
	g.emit("return nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── on_deinit ────────────────────────────────────────────────────

func (g *generator) genOnDeinit() {
	name := g.goStructName()
	g.emitf("func (s *%s) OnDeinit(ctx sdk.Context, reason string) error {", name)
	g.indent++
	if g.intent.Timer != nil {
		g.emit("ctx.KillTimer()")
	}
	g.emit(`if reason != "user_stop" && reason != "kill_switch" {`)
	g.emit("    return nil")
	g.emit("}")
	g.emit("s.closeAll(ctx)")
	g.emit("return nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── Helpers ──────────────────────────────────────────────────────

func (g *generator) genHelpers() {
	name := g.goStructName()
	g.emitf("func (s *%s) closeAll(ctx sdk.Context) {", name)
	g.indent++
	g.emit("for _, pos := range ctx.Broker().Positions(s.magic) {")
	g.emit("    ctx.Broker().PositionClose(pos.Ticket, decimal.Zero)")
	g.emit("}")
	g.emit("for _, ord := range ctx.Broker().Orders(s.magic) {")
	g.emit("    ctx.Broker().OrderDelete(ord.Ticket)")
	g.emit("}")
	g.indent--
	g.emit("}")
}

// ── Parameter emission ───────────────────────────────────────────

func (g *generator) emitParam(p ParamSpec) {
	dflt := p.Default
	switch p.Type {
	case ParamInt:
		if dflt == "" {
			dflt = "0"
		}
		g.emitf("s.%s = int32(ctx.ParamInt(\"%s\", %s))",
			p.Name, p.Name, dflt)
	case ParamDouble:
		if dflt == "" {
			dflt = "0"
		}
		g.emitf("s.%s = ctx.ParamDecimal(\"%s\", decimal.NewFromFloat(%s)).InexactFloat64()",
			p.Name, p.Name, dflt)
	case ParamString:
		if dflt == "" {
			dflt = `""`
		}
		g.emitf("s.%s = ctx.ParamString(\"%s\", \"%s\")",
			p.Name, p.Name, stripQuotes(dflt))
	case ParamBool:
		if dflt == "true" || dflt == "1" {
			dflt = "true"
		} else {
			dflt = "false"
		}
		g.emitf("s.%s = ctx.ParamBool(\"%s\", %s)", p.Name, p.Name, dflt)
	}
}

