// ── OnDeinit ──────────────────────────────────────────────────────

func (g *irGenerator) genOnDeinit() {
	g.curFunc = "OnDeinit"
	g.emitf("func (s *%s) OnDeinit(ctx sdk.Context, reason string) error {", g.name)
	g.indent++
	if len(g.ir.OnDeinit) > 0 {
		g.emitStmts(g.ir.OnDeinit)
	}
	g.emit("return nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── User-defined functions ────────────────────────────────────────

func (g *irGenerator) genUserFuncs() {
	for name, fn := range g.ir.Funcs {
		g.emitUserFunc(name, fn)
	}
}

func (g *irGenerator) emitUserFunc(name string, fn *interp.FuncDef) {
	g.curFunc = "userFunc"
	params := make([]string, len(fn.Params))
	for i, p := range fn.Params {
		params[i] = fmt.Sprintf("%s %s", p.Name, irParamGoType(p.Type))
	}
	g.emitf("func (s *%s) %s(%s) interface{} {", g.name, name, strings.Join(params, ", "))
	g.indent++
	if len(fn.Body) > 0 {
		g.emitStmts(fn.Body)
	}
	g.emit("return nil")
	g.indent--
	g.emit("}")
	g.emit("")
}

// ── Output helpers ────────────────────────────────────────────────

func (g *irGenerator) emit(s string) {
	g.b.WriteString(strings.Repeat("\t", g.indent))
	g.b.WriteString(s)
	g.b.WriteByte('\n')
}

func (g *irGenerator) emitf(format string, args ...interface{}) {
	g.emit(fmt.Sprintf(format, args...))
}

func (g *irGenerator) emitStmts(stmts []interp.Statement) {
	for i := range stmts {
		g.emitStmt(&stmts[i])
	}
}

// irParamGoType maps MQL type strings to Go types for struct fields.
func irParamGoType(t string) string {
	switch t {
	case "int", "long", "uint":
		return "int32"
	case "double", "float":
		return "decimal.Decimal"
	case "bool":
		return "bool"
	case "string":
		return "string"
	default:
		return "interface{}"
	}
}

func irPkgName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(unicode.ToLower(r))
		}
	}
	if b.Len() == 0 {
		return "strategy"
	}
	return b.String()
}

func isIntType(t string) bool {
	switch t {
	case "int", "long", "uint", "short", "char", "uchar", "ushort", "ulong":
		return true
	}
	return false
}
