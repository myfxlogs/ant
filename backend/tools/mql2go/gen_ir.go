	if len(g.ir.OnTimer) == 0 {
		return
	}
	g.emitf("func (s *%s) OnTimer(ctx sdk.Context) (*sdk.Signal, error) {", g.name)
	g.indent++
	g.emitStmts(g.ir.OnTimer)
